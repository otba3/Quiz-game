"""Bundle the exported question banks into one JavaScript file for the web game.

Browsers refuse to read local .json files when index.html is opened by
double-clicking (file://), but they do load <script src="..."> files.
So we wrap the JSON in a tiny JavaScript file:  const QUIZ_DATA = {...};

Run after the export scripts:  py scripts/build_web_data.py
"""
import json
from pathlib import Path

OUTPUT_DIR = Path("output")
WEB_DATA = Path("game/web/js/question_bank.js")
CATEGORIES = ["title", "year", "origin", "medium"]

LANGUAGES = ["en", "ar"]  # one output/i18n/<language>.json file each

data = {
    "texts": {lang: json.loads((OUTPUT_DIR / "i18n" / f"{lang}.json").read_text(encoding="utf-8"))
              for lang in LANGUAGES},
    "categories": {},
}
for name in CATEGORIES:
    bank = json.loads((OUTPUT_DIR / f"questions_{name}.json").read_text(encoding="utf-8"))
    data["categories"][name] = bank["questions"]

WEB_DATA.write_text(
    "// GENERATED by scripts/build_web_data.py from output.\n"
    "const QUIZ_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n",
    encoding="utf-8")

counts = {name: len(questions) for name, questions in data["categories"].items()}
print(f"Wrote {WEB_DATA} {counts}")
